import type { Scoreboard } from "./grade";

const tick = (passed: boolean) => (passed ? "pass" : "FAIL");

/** A scoreboard a human can read in a terminal. */
export function formatText(board: Scoreboard): string {
  const lines = [
    `Model: ${board.model}`,
    `Score: ${board.passed}/${board.total} cases passed`,
    `Tokens: ${board.usage.inputTokens} in / ${board.usage.outputTokens} out`,
    "",
  ];

  for (const result of board.cases) {
    lines.push(`[${tick(result.passed)}] ${result.id} - ${result.attack}`);
    if (result.error) lines.push(`   error: ${result.error}`);
    for (const c of result.checks) {
      lines.push(`   ${c.passed ? "ok  " : "MISS"} ${c.name} (${c.detail})`);
    }
    lines.push("");
  }

  return lines.join("\n");
}

/** A scoreboard that can be committed and diffed across runs. */
export function formatMarkdown(board: Scoreboard): string {
  const lines = [
    "# Adversarial eval scoreboard",
    "",
    `- **Model:** \`${board.model}\``,
    `- **Score:** ${board.passed}/${board.total}`,
    `- **Tokens:** ${board.usage.inputTokens} in / ${board.usage.outputTokens} out`,
    "",
    "| Case | Attack | Result | Failing checks |",
    "| --- | --- | --- | --- |",
  ];

  for (const result of board.cases) {
    const failing = result.checks.filter((c) => !c.passed).map((c) => c.name);
    lines.push(
      `| \`${result.id}\` | ${result.attack} | ${result.passed ? "pass" : "**FAIL**"} | ${
        failing.length ? failing.join("; ") : "-"
      } |`,
    );
  }

  lines.push(
    "",
    "Generated by `pnpm eval`. A failure means the model took an unsafe action that the",
    "guardrails did not already prevent - see `docs/ADVERSARIAL_CASES.md` for the control",
    "that covers each case.",
  );

  return lines.join("\n");
}
